const languagePreferenceKey = "agent-config-registry.language";

let locale = "zh-CN";
try {
  if (localStorage.getItem(languagePreferenceKey) === "en") locale = "en";
} catch {
  // The current session still supports language switching.
}

function setLocale(nextLocale) {
  locale = nextLocale;
  try {
    localStorage.setItem(languagePreferenceKey, nextLocale);
  } catch {
    // Some browsers restrict storage in isolated contexts.
  }
}

function t(message, values = {}) {
  const translated = locale === "zh-CN" ? (chineseMessages[message] ?? message) : message;
  return translated.replace(/\{(\w+)\}/g, (token, key) => values[key] ?? token);
}

